"""Build compatible Phosphor subsets from theme/plugin code, never at request time."""
import argparse, hashlib, io, json, re
from pathlib import Path

THEME = Path(__file__).resolve().parents[2]
PLUGIN = THEME.parents[1] / 'plugins/revayat-companion'
OUTPUT = Path(__file__).resolve().parent / 'dist'
WEIGHTS = {'regular': ('ph', 'Phosphor'), 'bold': ('ph-bold', 'Phosphor-Bold'), 'fill': ('ph-fill', 'Phosphor-Fill')}

def usage():
    explicit, literals, sources = set(), set(), {}
    catalog = set(re.findall(r'\.ph\.ph-([\w-]+):before', (THEME / 'assets/vendor/phosphor/regular/style.css').read_text()))
    for root in [THEME, PLUGIN]:
        for path in sorted(root.rglob('*')):
            if not path.is_file() or path.suffix not in {'.php', '.js'} or any(p in {'vendor', 'dist', '.git', 'node_modules'} for p in path.parts):
                continue
            blob = path.read_bytes()
            code = blob.decode('utf-8')
            explicit.update(re.findall(r'\bph-([a-z][a-z0-9-]*)', code))
            # Includes names used in ternary/string-built classes, even in hidden states.
            literals.update(re.findall(r"['\"]([a-z][a-z0-9-]*)['\"]", code))
            if 'ph-' in code:
                relevant = sorted(set(re.findall(r'\bph-([a-z][a-z0-9-]*)', code)) | (set(re.findall(r"['\"]([a-z][a-z0-9-]*)['\"]", code)) & catalog))
                sources[str(path.relative_to(THEME.parents[1]))] = hashlib.sha256(json.dumps(relevant).encode()).hexdigest()
    return explicit - {'bold', 'fill', 'light', 'thin', 'duotone'}, literals, sources

def build(check=False):
    explicit, literals, sources = usage()
    manifest = {'sources': sources, 'weights': {}}
    files, css = {}, []
    for weight, (class_name, family) in WEIGHTS.items():
        vendor = THEME / 'assets/vendor/phosphor' / weight
        original = (vendor / 'style.css').read_text()
        rules = dict(re.findall(r'\.' + re.escape(class_name) + r'\.ph-([\w-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}', original))
        missing = explicit - rules.keys()
        if missing:
            raise RuntimeError(f'Unmapped {weight} icons: {sorted(missing)}')
        names = sorted(explicit | (literals & rules.keys()))
        points = sorted({int(rules[name], 16) for name in names})
        # FontTools is build-only; --check does not require it on the packaging host.
        filename = family + '.woff2'
        if check:
            font_bytes = (OUTPUT / filename).read_bytes()
        else:
            from fontTools import subset
            from fontTools.ttLib import TTFont
            font = TTFont(vendor / (family + '.woff2'), recalcTimestamp=False)
            options = subset.Options()
            options.flavor = 'woff2'
            options.name_IDs = ['*']
            sub = subset.Subsetter(options=options)
            sub.populate(unicodes=points)
            sub.subset(font)
            font.flavor = 'woff2'
            buf = io.BytesIO()
            font.save(buf)
            font_bytes = buf.getvalue()
        files[filename] = font_bytes
        font_hash = hashlib.sha256(font_bytes).hexdigest()[:16]
        face = f'@font-face{{font-family:"{family}";src:url("./{filename}?ver={font_hash}") format("woff2");font-weight:normal;font-style:normal;font-display:swap;}}'
        base = re.search(r'\.' + re.escape(class_name) + r'\s*\{([\s\S]*?)\}', original).group(1)
        base = re.sub(r'/\*[\s\S]*?\*/', '', base)
        base = re.sub(r'\s+', ' ', base).strip()
        css.append(face + f'.{class_name}' + '{' + base + '}')
        css.extend(f'.{class_name}.ph-{name}:before' + '{content:"\\' + rules[name] + '";}' for name in names)
        manifest['weights'][weight] = {'names': names, 'unicodes': points, 'file': filename, 'bytes': len(font_bytes), 'sha256': hashlib.sha256(font_bytes).hexdigest()}
    content = ('\n'.join(css) + '\n').encode()
    files['icons.css'] = content
    version = hashlib.sha256(content).hexdigest()[:16]
    manifest['version'] = version
    files['manifest.json'] = (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode()
    files['manifest.php'] = ("<?php\n// Generated by assets/icons/build-icons.py.\nreturn ['file' => '/assets/icons/dist/icons.css', 'version' => '" + version + "'];\n").encode()
    OUTPUT.mkdir(exist_ok=True)
    for name, blob in files.items():
        path = OUTPUT / name
        if check:
            if not path.exists() or path.read_bytes() != blob:
                raise RuntimeError('Stale icon build: ' + name)
        elif not path.exists() or path.read_bytes() != blob:
            path.write_bytes(blob)
    print(('Verified' if check else 'Built') + f' Phosphor subsets: {len(names)} names × {len(WEIGHTS)} weights; CSS/fonts {len(content) + sum(x["bytes"] for x in manifest["weights"].values())} bytes')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
